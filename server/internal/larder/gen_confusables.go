//go:build ignore

// gen_confusables writes confusables.go, the table nameKey uses, from
// Unicode's confusables.txt (UTS #39). Run it with go generate. A new table
// changes name keys, so it needs a migration that recomputes name_key.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"maps"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/text/cases"
	"golang.org/x/text/unicode/norm"
)

// The Unicode version matches the tables golang.org/x/text uses under Go 1.27.
const source = "https://www.unicode.org/Public/17.0.0/security/confusables.txt"

func main() {
	res, err := http.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", source, res.Status)
	}

	// nameKey folds case before it looks a character up, so a capital's
	// prototype moves to its lowercase letter and wins over that letter's
	// own: "I" → "l" gives "i" → "l", and Cyrillic "Н" → "H" gives "н" → "h".
	own, capital := map[rune]string{}, map[rune]string{}
	sc := bufio.NewScanner(res.Body)
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		f := strings.Split(line, ";")
		if len(f) < 2 {
			continue
		}
		src, proto := decode(f[0]), fold(decode(f[1]))
		r, lower := []rune(src)[0], []rune(fold(src))
		if string(lower) == src {
			own[r] = proto
		} else if unicode.IsUpper(r) && len(lower) == 1 {
			capital[lower[0]] = proto
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	maps.Copy(own, capital)

	// Map each prototype until it stops changing, so one pass in nameKey is enough.
	table := map[rune]string{}
	for r, p := range own {
		for i := 0; ; i++ {
			next := skeleton(p, own)
			if next == p {
				break
			}
			if i == 10 {
				log.Fatalf("%U: the prototype does not settle", r)
			}
			p = next
		}
		if p != string(r) && norm.NFD.String(string(r)) == string(r) {
			table[r] = p
		}
	}
	for r, p := range table {
		if skeleton(p, table) != p {
			log.Fatalf("%U: nameKey would change the key %+q", r, p)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_confusables.go from %s; DO NOT EDIT.\n\npackage larder\n\n", source)
	b.WriteString("// confusables maps a case-folded NFD character to its prototype.\nvar confusables = map[rune]string{\n")
	for _, r := range slices.Sorted(maps.Keys(table)) {
		fmt.Fprintf(&b, "0x%04X: %+q,\n", r, table[r])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("confusables.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// skeleton is nameKey with the table m.
func skeleton(s string, m map[rune]string) string {
	var b strings.Builder
	for _, r := range norm.NFD.String(fold(s)) {
		if p, ok := m[r]; ok {
			b.WriteString(p)
		} else {
			b.WriteRune(r)
		}
	}
	return norm.NFD.String(b.String())
}

func fold(s string) string { return cases.Fold().String(s) }

// decode turns space-separated hex code points into a string.
func decode(hex string) string {
	var s []rune
	for _, h := range strings.Fields(hex) {
		n, err := strconv.ParseUint(h, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		s = append(s, rune(n))
	}
	return string(s)
}
